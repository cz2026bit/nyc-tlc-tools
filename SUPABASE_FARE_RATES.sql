create table if not exists fare_rates (
  id bigint generated by default as identity primary key,
  service_id text not null,
  service_name text not null,
  zone text not null check (zone in ('inside', 'outside')),
  zone_label text not null default 'New York City',
  mile_rate numeric(10, 4) not null default 0,
  minute_rate numeric(10, 4) not null default 0,
  base_fare numeric(10, 4) not null default 0,
  pickup_fee_label text,
  pickup_threshold text default '9 minutes',
  wait_minute_rate numeric(10, 4),
  reservation_classes jsonb not null default '["ECONOMY"]'::jsonb,
  reservation_min_fare numeric(10, 4) not null default 0,
  reservation_fee numeric(10, 4) not null default 0,
  fixed_cancel_fee numeric(10, 4) not null default 0,
  cancel_policy text not null default 'FIXED FEE',
  minimum_trip_income numeric(10, 4) not null default 0,
  driver_cancel_fee numeric(10, 4) not null default 0,
  rider_cancel_fee numeric(10, 4) not null default 0,
  sort_order integer not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  unique (service_id, zone)
);

